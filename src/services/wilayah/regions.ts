export function provinceName(code: string): string | undefined {
  return PROVINCES.find((entry) => entry[0] === code)?.[1];
}

export function provinceCodes(): string[] {
  return PROVINCES.map((entry) => entry[0]);
}

export function regenciesOfProvince(provCode: string): RegionRegency[] {
  return (REGENCIES[provCode] ?? []).map(([code, name, tipe]) => ({ code, name, kind: tipe === 2 ? "kota" : "kab" }));
}

